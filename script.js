let currentLang = 'en';
const NAVBAR_OFFSET = 84;

function switchLanguage(lang) {
	if (! translations[lang]) {
		return;
	}

	document.querySelectorAll('[data-translate]').forEach(
		(element) => {
			const key = element.getAttribute('data-translate');
			const value = translations[lang][key];
			if (value) {
				element.textContent = value;
			}
		}
	);

	document.documentElement.lang = lang;
	localStorage.setItem('preferredLanguage', lang);
}

function updateActivePage() {
	const currentPage = document.body.dataset.page;
	document.querySelectorAll('.nav-link[data-nav]').forEach(
			(link) => {
			if (link.dataset.nav === currentPage) {
				link.setAttribute('aria-current', 'page');
			} else {
				link.removeAttribute('aria-current');
			}
		}
	);
}

function closeMenu(navMenu, hamburger) {
	navMenu.classList.remove('active');
	hamburger.setAttribute('aria-expanded', 'false');
	const spans = hamburger.querySelectorAll('span');
	spans[0].style.transform = 'none';
	spans[1].style.opacity = '1';
	spans[2].style.transform = 'none';
}

function toggleMenu(navMenu, hamburger) {
	navMenu.classList.toggle('active');
	const isOpen = navMenu.classList.contains('active');
	hamburger.setAttribute('aria-expanded', String(isOpen));
	const spans = hamburger.querySelectorAll('span');
	spans[0].style.transform = isOpen ? 'rotate(45deg) translate(5px, 5px)' : 'none';
	spans[1].style.opacity = isOpen ? '0' : '1';
	spans[2].style.transform = isOpen ? 'rotate(-45deg) translate(6px, -6px)' : 'none';
}

document.addEventListener(
	'DOMContentLoaded', () => {
		const year = document.getElementById('year');
		if (year) {
			year.textContent = new Date().getFullYear();
		}

		updateActivePage();

		const hamburger = document.querySelector('.hamburger');
		const navMenu = document.querySelector('.nav-menu');
		if (hamburger && navMenu) {
			hamburger.addEventListener('click', () => toggleMenu(navMenu, hamburger));
			navMenu.querySelectorAll('a').forEach(
				(link) => {
					link.addEventListener('click', () => closeMenu(navMenu, hamburger));
				}
			);
		}

		document.querySelectorAll('a[href^="#"]').forEach(
			(anchor) => {
				anchor.addEventListener(
					'click', (event) => {
						const target = document.querySelector(anchor.getAttribute('href'));
						if (! target) {
							return;
						}

						event.preventDefault();
						const offsetTop = target.getBoundingClientRect().top + window.scrollY - NAVBAR_OFFSET;
						window.scrollTo({ top: offsetTop, behavior: 'smooth' });
					}
				);
			}
		);

		const langButtons = document.querySelectorAll('.lang-btn');
		langButtons.forEach((button) => {
			button.addEventListener(
					'click', () => {
						const lang = button.dataset.lang;
						if (! lang || lang === currentLang) {
							return;
						}

						currentLang = lang;
						switchLanguage(lang);
						langButtons.forEach((btn) => btn.classList.toggle('active', btn === button));
					}
				);
			}
		);

		const savedLang = localStorage.getItem('preferredLanguage');
		if (savedLang && translations[savedLang]) {
			currentLang = savedLang;
			switchLanguage(savedLang);
			langButtons.forEach((button) => button.classList.toggle('active', button.dataset.lang === savedLang));
		}
	}
);
